"""Build manuscript figures and LaTeX tables from recorded experiment data."""
from pathlib import Path
import csv
import json
import xml.etree.ElementTree as ET

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import Normalize
import numpy as np

HERE = Path(__file__).resolve().parent
DATA, FIG, GEN = HERE / "data", HERE / "figures", HERE / "generated"


def write_rows(filename, command, rows):
    (GEN / filename).write_text(
        "\\newcommand{\\" + command + "}{%\n" + "\n".join(rows) + "\n}\n")


def main():
    FIG.mkdir(exist_ok=True)
    GEN.mkdir(exist_ok=True)
    plt.rcParams.update({"font.size": 9, "axes.titlesize": 10, "axes.labelsize": 9,
                         "legend.fontsize": 8, "pdf.fonttype": 42, "ps.fonttype": 42,
                         "savefig.dpi": 300, "axes.spines.top": False, "axes.spines.right": False})
    records = {item["name"]: item for item in json.loads((DATA / "experiments.json").read_text())}
    c, f = records["coupled"]["final"], records["fisher_kpp"]["final"]
    n = records["coupled_dx1"]["final"]
    nf = records["fisher_kpp_dx1"]["final"]
    macros = dict(CoupledCells=f"{c['cells']/1e9:.3f}", ReferenceCells=f"{f['cells']/1e9:.3f}",
                  CellReduction=f"{100*(1-c['cells']/f['cells']):.2f}",
                  VolumeReduction=f"{100*(1-c['volume_20_ml']/f['volume_20_ml']):.2f}",
                  CoupledVolume=f"{c['volume_20_ml']:.3f}", ReferenceVolume=f"{f['volume_20_ml']:.3f}",
                  CoupledPeak=f"{c['max_density']/1e5:.3f}", ReferencePeak=f"{f['max_density']/1e5:.3f}",
                  NecroticCells=f"{c['necrotic_cells']/1e6:.3f}", NecroticVolume=f"{c['necrotic_volume_20_ml']:.3f}",
                  MinimumOxygen=f"{c['min_oxygen']:.4f}", MaximumNecrosis=f"{c['max_necrosis_over_K']:.3f}",
                  NativeMinimumOxygen=f"{n['min_oxygen']:.4f}", NativeMaximumNecrosis=f"{n['max_necrosis_over_K']:.3f}",
                  NativeCellReduction=f"{100*(1-n['cells']/nf['cells']):.2f}",
                  CellGapMillion=f"{(f['cells']-c['cells'])/1e6:.2f}",
                  BirthGapMillion=f"{(f['cells']-c['cells']-c['necrotic_cells'])/1e6:.2f}",
                  ZeroUptakeError=f"{json.loads((DATA/'provenance.json').read_text())['zero_uptake_max_absolute_error_over_K']:.2e}")
    xml = ET.parse(DATA / "pytest.xml").getroot()
    macros["TestCount"] = str(sum(int(e.attrib.get("tests",0)) for e in xml.iter("testsuite")))
    (GEN / "numbers.tex").write_text("% Generated by make_figures.py; do not edit.\n" +
        "\n".join(r"\newcommand{\%s}{%s}" % (k,v) for k,v in macros.items()) + "\n")

    rows = []
    labels = {"fisher_kpp": r"M0: Fisher--KPP", "oxygen_only": r"M1: oxygen-limited growth",
              "coupled": r"M2: oxygen and necrosis", "fixed_supply": r"M2, fixed supply ($\alpha=0$)",
              "zero_uptake": r"M2, zero uptake ($\beta=0$)"}
    for key in labels:
        m = records[key]["final"]
        oxygen = f"{m['min_oxygen']:.4f}" if 'min_oxygen' in m else r"---"
        dead = f"{m['necrotic_cells']/1e6:.3f}" if 'necrotic_cells' in m else r"---"
        rows.append(f"{labels[key]} & {m['cells']/1e9:.3f} & {m['volume_20_ml']:.3f} & "
                    f"{m['volume_80_ml']:.3f} & {oxygen} & {dead} " + r"\\")
    write_rows("ablation_rows.tex", "AblationRows", rows)
    rows=[]
    for key in ("coupled","coupled_dt0125","coupled_dt00625","coupled_dx1"):
        rec=records[key]; m=rec['final']
        rows.append(f"{rec['spacing_mm']:g} & {rec['dt_days']:g} & {m['cells']/1e9:.4f} & "
                    f"{m['necrotic_cells']/1e6:.4f} & {m['min_oxygen']:.4f} & {m['max_necrosis_over_K']:.3f} " + r"\\")
    write_rows("refinement_rows.tex", "RefinementRows", rows)
    rows=[]
    for key in ('coupled','coupled_dt0125'):
        rec=records[key]; err=rec['errors_against_dt00625']
        rows.append(f"{rec['dt_days']:g} & {100*err['density']['relative_l2']:.4f} & "
                    f"{100*err['oxygen']['relative_l2']:.4f} & {100*err['necrosis']['relative_l2']:.3f} " + r"\\")
    write_rows("error_rows.tex", "ErrorRows", rows)

    a=np.load(DATA / 'day90_planes.npz')
    affine=a['affine']; indices=a['indices']; xyz=(affine@np.r_[indices,1])[:3]; h=float(a['spacing_mm']); K=float(a['K'])
    styles=[('viable','Coupled viable tumor','inferno',1.),('reference','Fisher--KPP reference','inferno',1.),
            ('oxygen','Relative oxygen','viridis',1.),('necrosis','Necrotic material','magma',1.3)]
    orientation={'Axial':(0,1,2,('L','R','P','A')),'Coronal':(0,2,1,('L','R','I','S')),
                 'Sagittal':(1,2,0,('P','A','I','S'))}

    def panel(ax,view,plane,cmap,vmax):
        ia,ib,ic,dirs=orientation[plane]
        bg=a[f'background_{plane}']; v=a[f'{view}_{plane}']; v=v if view=='oxygen' else v/K
        x=affine[ia,3]+np.arange(bg.shape[0])*h
        y=affine[ib,3]+np.arange(bg.shape[1])*h
        extent=(x[0]-h/2,x[-1]+h/2,y[0]-h/2,y[-1]+h/2)
        ax.imshow(bg.T,origin='lower',extent=extent,cmap='gray',vmin=0,vmax=1,interpolation='nearest')
        rgba=matplotlib.colormaps[cmap](Normalize(0,vmax)(v.T))
        visible=a[f'mask_{plane}'] if view=='oxygen' else v>=.02
        rgba[...,3]=np.where(visible.T,.88,0)
        ax.imshow(rgba,origin='lower',extent=extent,interpolation='nearest')
        if view in ('viable','reference'):
            for field,color,ls in [('viable','white','-'),('reference','#54d5ff','--')]:
                ax.contour(x,y,(a[f'{field}_{plane}']/K).T,levels=[.2],colors=[color],linestyles=[ls],linewidths=.8)
        ax.set(xlim=(xyz[ia]-36,xyz[ia]+36),ylim=(xyz[ib]-36,xyz[ib]+36))
        ax.set_aspect('equal');ax.set_axis_off()
        for px,py,s in ((.035,.5,dirs[0]),(.965,.5,dirs[1]),(.5,.035,dirs[2]),(.5,.965,dirs[3])):
            ax.text(px,py,s,transform=ax.transAxes,color='white',fontsize=7,ha='center',va='center',
                    bbox=dict(facecolor='black',alpha=.6,edgecolor='none',pad=.5))
        return matplotlib.cm.ScalarMappable(norm=Normalize(0,vmax),cmap=cmap)

    fig,axes=plt.subplots(2,2,figsize=(6.6,6.7),layout='constrained')
    for idx,(view,title,cmap,vmax) in enumerate(styles):
        ax=axes.flat[idx]; m=panel(ax,view,'Axial',cmap,vmax)
        ax.set_title(f"{'abcd'[idx]}. {title}",loc='left',fontweight='bold',fontsize=10)
        cb=fig.colorbar(m,ax=ax,orientation='horizontal',fraction=.047,pad=.018,shrink=.91)
        cb.ax.tick_params(labelsize=7)
        cb.set_label('Relative to normal baseline' if view=='oxygen' else ('z / K' if view=='necrosis' else 'c / K'),fontsize=8,labelpad=1)
    ax=axes[0,0];sx,sy=xyz[0]-28,xyz[1]-28
    ax.plot([sx,sx+10],[sy,sy],color='white',lw=2);ax.text(sx+5,sy+3,'10 mm',color='white',ha='center',fontsize=7)
    fig.savefig(FIG/'day90_fields.pdf');fig.savefig(FIG/'day90_fields.png');plt.close(fig)

    fig,axes=plt.subplots(2,4,figsize=(7.,4.8),layout='constrained')
    for row,plane in enumerate(('Coronal','Sagittal')):
        for col,(view,title,cmap,vmax) in enumerate(styles):
            ax=axes[row,col];m=panel(ax,view,plane,cmap,vmax)
            ax.set_title(f'{plane}: {title}',fontsize=7)
            if row==1:
                cb=fig.colorbar(m,ax=ax,orientation='horizontal',fraction=.045,pad=.02)
                cb.ax.tick_params(labelsize=6)
                cb.set_label('o' if view=='oxygen' else ('z / K' if view=='necrosis' else 'c / K'),fontsize=7)
    fig.savefig(FIG/'orthogonal_fields.pdf');fig.savefig(FIG/'orthogonal_fields.png');plt.close(fig)

    curves={}
    for row in csv.DictReader((DATA/'timecourses.csv').open()):
        curves.setdefault(row['experiment'],[]).append({k:float(v) if v else np.nan for k,v in row.items() if k!='experiment'})
    colors={'fisher_kpp':'#202020','oxygen_only':'#247ba0','coupled':'#c0392b','fixed_supply':'#a76b00'}
    linestyles={'fisher_kpp':'-','oxygen_only':'--','coupled':'-','fixed_supply':':'}
    titles={'fisher_kpp':'M0: Fisher--KPP','oxygen_only':'M1: oxygen only','coupled':'M2: coupled','fixed_supply':'M2: fixed supply'}
    fig,axes=plt.subplots(2,2,figsize=(6.8,5.0),layout='constrained')
    for key in colors:
        t=np.array([v['time_days'] for v in curves[key]])
        for ax,metric,scale in [(axes[0,0],'cells',1e9),(axes[0,1],'volume_20_ml',1),(axes[1,0],'min_oxygen',1),(axes[1,1],'necrotic_cells',1e6)]:
            vals=np.array([v[metric] for v in curves[key]])/scale
            if np.any(np.isfinite(vals)):
                ax.plot(t,vals,color=colors[key],ls=linestyles[key],lw=1.5,label=titles[key])
    labels=[('a. Viable tumor burden','Viable cells (billions)'),('b. Threshold-defined extent','Volume at c / K >= 0.2 (mL)'),
            ('c. Minimum tissue oxygen','Relative oxygen'),('d. Accumulated necrotic material','Cell equivalents (millions)')]
    for ax,(title,label) in zip(axes.flat,labels):
        ax.set(xlabel='Time (days)',ylabel=label,xlim=(0,90));ax.set_title(title,loc='left',fontsize=9.5)
        ax.grid(alpha=.2);ax.tick_params(labelsize=8)
    axes[1,0].axhline(.1,color='#555',lw=.8,ls='--');axes[1,0].text(3,.105,'Death threshold',fontsize=7,color='#555',va='bottom')
    axes[0,0].legend(frameon=False,loc='upper left',fontsize=7)
    fig.savefig(FIG/'timecourses.pdf');fig.savefig(FIG/'timecourses.png');plt.close(fig)
    print('Generated three vector figures, preview PNGs, numerical macros and tables.')


if __name__=='__main__':
    main()
