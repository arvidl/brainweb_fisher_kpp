"""Build PAT16 manuscript assets from checked compact public results, without MRI."""
from pathlib import Path
import csv
import hashlib
import json
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / 'scripts'))
from export_pat16_results import notebook_code_hash


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    output = ROOT / 'outputs/pat16_pilot'
    manifest = json.loads((output / 'exports.json').read_text())
    for name, entry in manifest['files'].items():
        if digest(output / name) != entry['sha256']:
            raise RuntimeError(f'Stale PAT16 export: {name}')
    provenance = json.loads((output / 'provenance.json').read_text())
    for name, expected in provenance['software_sha256'].items():
        if digest(ROOT / 'src/brainweb_kpp' / name) != expected:
            raise RuntimeError(f'Stale PAT16 code: {name}; rerun notebook and export')
    if notebook_code_hash(ROOT / 'pat16_anisotropic_pilot.ipynb') != manifest['notebook_code_sha256']:
        raise RuntimeError('PAT16 notebook code changed; rerun notebook and export')
    z = np.load(output / 'sample_metrics.npz')
    fields = np.load(output / 'summary_fields.npz')
    summary = json.loads((output / 'summary.json').read_text())
    for key, report in [('burden_ml', 'burden_ml_q05_q50_q95'),
                        ('volume_ml', 'threshold_volume_ml_q05_q50_q95')]:
        np.testing.assert_allclose(np.quantile(z[key], [.05, .5, .95], axis=0), summary[report])
        metric = 'burden' if key == 'burden_ml' else 'volume'
        np.testing.assert_allclose(np.quantile(z[key][:, 1, -1] - z[key][:, 0, -1], [.05, .5, .95]),
                                   summary[f'paired_final_{metric}_difference_ml_q05_q50_q95'])
    check = json.loads((output / 'verification.json').read_text())
    macros = {'PATScenarios': str(summary['scenario_count']),
              'PATBurdenDifference': f"{summary['paired_final_burden_difference_ml_q05_q50_q95'][1]:.2f}",
              'PATTimeDifference': f"{100*check['representative_day90_dt_half_relative_L1']:.3f}",
              'PATFAR': f"{provenance['fa_alignment_correlation']:.4f}"}
    (HERE / 'generated/pat16_numbers.tex').write_text('% Generated by make_pat16_figures.py\n' +
        '\n'.join(r'\newcommand{\%s}{%s}' % (key, value) for key, value in macros.items()) + '\n')
    rows = []
    for key, label in [('burden_ml', r'$\int u\,\dd V$ (mL equivalents)'),
                        ('volume_ml', r'$V(u\geq0.16)$ (mL)')]:
        values = [z[key][:, model, -1] for model in (0, 1)]
        values.append(values[1] - values[0])
        cells = []
        for value in values:
            low, med, high = np.quantile(value, [.05, .5, .95])
            cells.append(f'{med:.2f} [{low:.2f}, {high:.2f}]')
        rows.append(label + ' & ' + ' & '.join(cells) + r'\\')
    (HERE / 'generated/pat16_rows.tex').write_text(r'\newcommand{\PATRows}{%' + '\n' + '\n'.join(rows) + '\n}\n')
    plt.rcParams.update({'font.size': 8, 'axes.titlesize': 8, 'axes.labelsize': 8,
                         'legend.fontsize': 7, 'pdf.fonttype': 42, 'savefig.dpi': 300})
    fig, axes = plt.subplots(2, 2, figsize=(7.0, 6.4), layout='constrained')
    shape, affine = tuple(fields['shape']), fields['affine']
    index = int(fields['axial_index'])
    spacing = affine[0, 0]
    extent = [affine[0, 3] - spacing/2, affine[0, 3] + (shape[0]-.5)*spacing,
              affine[1, 3] - spacing/2, affine[1, 3] + (shape[1]-.5)*spacing]
    def plane(values):
        full = np.zeros(shape, dtype='float32')
        full.ravel()[fields['active']] = values
        return full[:, :, index].T
    delta = plane(fields['paired_median_difference'][-1])
    delta_limit = np.ceil(max(.02, np.max(np.abs(delta)))*100)/100
    specs = [(plane(fields['density_quantiles'][1, 0, -1]), '(a) Isotropic median', 'inferno', 0, 1, 'Normalized density'),
             (plane(fields['density_quantiles'][1, 1, -1]), '(b) Anisotropic median', 'inferno', 0, 1, 'Normalized density'),
             (delta, '(c) Paired median difference', 'RdBu_r', -delta_limit, delta_limit, 'Anisotropic - isotropic'),
             (plane(fields['anisotropic_exceedance_fraction'][-1]), '(d) Anisotropic exceedance fraction', 'viridis', 0, 1, 'Fraction with u >= 0.16')]
    center = fields['lesion_center_RAS_mm']
    centers = fields['roi_centers_RAS_mm']
    visible = abs(centers[:, 2] - (affine[2, 3] + spacing*index)) <= 12
    i, j = np.triu_indices(len(centers), 1)
    use = visible[i] & visible[j] & (abs(z['fc'][i, j]) >= .35)
    pairs = sorted(zip(i[use], j[use]), key=lambda pair: abs(z['fc'][pair]))[-35:]
    for number, (ax, (value, title, cmap, low, high, label)) in enumerate(zip(axes.flat, specs)):
        ax.imshow(fields['t1_axial'], origin='lower', extent=extent, cmap='gray', vmin=0, vmax=1)
        image = np.ma.masked_where(abs(value) < (.005 if number == 2 else .02), value)
        artist = ax.imshow(image, origin='lower', extent=extent, cmap=cmap, vmin=low, vmax=high, alpha=.85)
        ax.contour(fields['lesion_axial'], levels=[.5], origin='lower', extent=extent,
                   colors=['#52ff8f'], linewidths=.6)
        if number < 2:
            for a, b in pairs:
                ax.plot(centers[[a, b], 0], centers[[a, b], 1], lw=.5, alpha=.6,
                        color='#30d5c8' if z['fc'][a, b] > 0 else '#b5a0ff')
        ax.set(title=title, xlabel='R (mm)', ylabel='A (mm)',
               xlim=(center[0]-52, center[0]+52), ylim=(center[1]-55, center[1]+55))
        fig.colorbar(artist, ax=ax, shrink=.75, label=label, pad=.02)
    for suffix in ['pdf', 'png']:
        fig.savefig(HERE / f'figures/pat16_fields.{suffix}')
    plt.close(fig)
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.9), layout='constrained')
    for panel, (key, label) in enumerate([('burden_ml', 'Normalized burden (mL equivalents)'),
                                          ('volume_ml', 'Volume u >= 0.16 (mL)')]):
        ax = axes[panel]
        for model, (name, color) in enumerate([('isotropic', '#2979b8'), ('anisotropic', '#c65d1c')]):
            low, med, high = np.quantile(z[key][:, model], [.05, .5, .95], axis=0)
            ax.fill_between(z['times'], low, high, color=color, alpha=.16)
            ax.plot(z['times'], med, label=name, color=color)
        ax.set(xlabel='Conditional time (days)', ylabel=label, xlim=(0, 90), title=f'({"ab"[panel]})')
        ax.legend(loc='upper left', frameon=False)
    for suffix in ['pdf', 'png']:
        fig.savefig(HERE / f'figures/pat16_timecourses.{suffix}')
    plt.close(fig)
    print('PAT16 source/export hashes and metrics verified; vector figures and tables generated.')


if __name__ == '__main__':
    main()
